// Generador DDL por dialecto (PostgreSQL, MySQL, SQLite, SQL Server).
import type { Column, Dialect, Schema, Table, View } from '@/types/schema'

import { dialectWarnings, generateProceduralSQL } from '@/features/triggers/lib/sql'
import { orderViews } from '@/lib/importers/views'

import {
  DIALECT_LABELS,
  columnTypeSQL,
  enumCheckSQL,
  findEnum,
  indexName,
  lineComment,
  mapDefault,
  quoteIdent,
  referentialSQL,
  relationConstraintName,
  resolveRelations,
  sqlString,
  uniqueConstraintName,
  type ResolvedRelation,
} from './dialects'

export interface GenerateSQLOptions {
  /** Añade DROP ... IF EXISTS antes de crear (por defecto false). */
  includeDrop?: boolean
  /** Comentarios de tablas/columnas (COMMENT ON / COMMENT / extended properties). Por defecto true. */
  includeComments?: boolean
  /** Funciones y triggers (solo PostgreSQL). Por defecto true. */
  includeTriggers?: boolean
  /** Cabecera con fecha y dialecto. Por defecto true. */
  header?: boolean
}

// ---------------------------------------------------------------------------
// Funciones y triggers: se delega en la feature de triggers
// (generateProceduralSQL de src/features/triggers/lib/sql.ts, que usa generateTriggerSQL).
// `registerTriggerSQL` permite sustituirlo; `simpleTriggerSQL` es el último recurso.
// ---------------------------------------------------------------------------
type TriggerSQLProvider = (schema: Schema, dialect: Dialect) => string
let triggerSQLProvider: TriggerSQLProvider | null = null

export function registerTriggerSQL(fn: TriggerSQLProvider | null) {
  triggerSQLProvider = fn
}

const q = quoteIdent

/** Orden topológico: primero las tablas referenciadas. Los ciclos se resuelven con ALTER TABLE. */
export function orderTables(schema: Schema): Table[] {
  const deps = new Map<string, Set<string>>()
  for (const t of schema.tables) deps.set(t.id, new Set())
  for (const r of schema.relations) {
    if (r.sourceTableId !== r.targetTableId) deps.get(r.targetTableId)?.add(r.sourceTableId)
  }
  const out: Table[] = []
  const state = new Map<string, 1 | 2>()
  const visit = (t: Table) => {
    if (state.get(t.id)) return
    state.set(t.id, 1)
    for (const d of deps.get(t.id) ?? []) {
      const dt = schema.tables.find((x) => x.id === d)
      if (dt && !state.get(dt.id)) visit(dt)
    }
    state.set(t.id, 2)
    out.push(t)
  }
  schema.tables.forEach(visit)
  return out
}

const isInlineAutoPk = (table: Table, col: Column, dialect: Dialect) =>
  dialect === 'sqlite' && col.autoIncrement && col.pk && table.columns.filter((c) => c.pk).length === 1

/** Definición de una columna (sin coma final). */
export function columnDefinitionSQL(
  schema: Schema,
  table: Table,
  col: Column,
  dialect: Dialect,
  opts: { skipUnique?: boolean; skipComment?: boolean } = {},
): string {
  const parts = [q(col.name, dialect)]
  if (isInlineAutoPk(table, col, dialect)) {
    parts.push('INTEGER PRIMARY KEY AUTOINCREMENT')
  } else {
    parts.push(columnTypeSQL(schema, col, dialect))
    if (col.autoIncrement) {
      if (dialect === 'postgresql') parts.push('GENERATED BY DEFAULT AS IDENTITY')
      else if (dialect === 'mysql') parts.push('AUTO_INCREMENT')
      else if (dialect === 'sqlserver') parts.push('IDENTITY(1,1)')
    }
  }
  if (!col.nullable || col.pk) parts.push('NOT NULL')
  if (col.unique && !col.pk && !opts.skipUnique) {
    parts.push(dialect === 'sqlserver' ? `CONSTRAINT ${q(uniqueConstraintName(table, col), dialect)} UNIQUE` : 'UNIQUE')
  }
  if (!col.autoIncrement) {
    let def = mapDefault(col.default, dialect, col)
    // Un default sin comillas sobre un enum ('activo' escrito como activo) se cita.
    if (def !== null && findEnum(schema, col.type)?.values.includes(def)) def = sqlString(def)
    if (def !== null) parts.push(`DEFAULT ${def}`)
  }
  const check = enumCheckSQL(schema, col, dialect)
  if (check) parts.push(check)
  if (dialect === 'mysql' && col.comment && !opts.skipComment) parts.push(`COMMENT ${sqlString(col.comment)}`)
  return parts.join(' ')
}

export function foreignKeyClause(schema: Schema, r: ResolvedRelation, dialect: Dialect): string {
  const parts = [
    `CONSTRAINT ${q(relationConstraintName(schema, r.rel), dialect)} FOREIGN KEY (${q(r.targetColumn.name, dialect)})`,
    `REFERENCES ${q(r.source.name, dialect)} (${q(r.sourceColumn.name, dialect)})`,
  ]
  const del = referentialSQL(r.rel.onDelete, dialect)
  const upd = referentialSQL(r.rel.onUpdate, dialect)
  if (del) parts.push(`ON DELETE ${del}`)
  if (upd) parts.push(`ON UPDATE ${upd}`)
  return parts.join(' ')
}

export function addForeignKeySQL(schema: Schema, r: ResolvedRelation, dialect: Dialect): string {
  if (dialect === 'sqlite') return lineComment(`SQLite no permite añadir FKs con ALTER TABLE: ${relationConstraintName(schema, r.rel)}`)
  return `ALTER TABLE ${q(r.target.name, dialect)} ADD ${foreignKeyClause(schema, r, dialect)};`
}

export function createIndexSQL(table: Table, idx: Table['indexes'][number], dialect: Dialect): string | null {
  const cols = idx.columnIds.map((id) => table.columns.find((c) => c.id === id)).filter(Boolean) as Column[]
  if (!cols.length) return null
  return `CREATE ${idx.unique ? 'UNIQUE ' : ''}INDEX ${q(indexName(table, idx), dialect)} ON ${q(table.name, dialect)} (${cols
    .map((c) => q(c.name, dialect))
    .join(', ')});`
}

const sqlServerDescription = (value: string, table: string, column?: string) =>
  `EXEC sp_addextendedproperty @name = N'MS_Description', @value = N${sqlString(value)}, @level0type = N'SCHEMA', @level0name = N'dbo', @level1type = N'TABLE', @level1name = N${sqlString(table)}${
    column ? `, @level2type = N'COLUMN', @level2name = N${sqlString(column)}` : ''
  };`

export function createTableSQL(schema: Schema, table: Table, dialect: Dialect, inlineFks: ResolvedRelation[] = []): string {
  const lines = table.columns.map((c) => '  ' + columnDefinitionSQL(schema, table, c, dialect))
  const pk = table.columns.filter((c) => c.pk)
  const inlinePk = pk.length === 1 && isInlineAutoPk(table, pk[0], dialect)
  if (pk.length && !inlinePk) lines.push(`  PRIMARY KEY (${pk.map((c) => q(c.name, dialect)).join(', ')})`)
  for (const fk of inlineFks) lines.push('  ' + foreignKeyClause(schema, fk, dialect))
  let sql = `CREATE TABLE ${q(table.name, dialect)} (\n${lines.join(',\n')}\n)`
  if (dialect === 'mysql') {
    sql += ' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4'
    if (table.comment) sql += ` COMMENT=${sqlString(table.comment)}`
  }
  sql += ';'
  if (dialect === 'sqlite' && table.comment) sql = `${lineComment(table.comment)}\n${sql}`
  return sql
}

function commentStatements(table: Table, dialect: Dialect): string[] {
  const out: string[] = []
  if (dialect === 'postgresql') {
    if (table.comment) out.push(`COMMENT ON TABLE ${q(table.name, dialect)} IS ${sqlString(table.comment)};`)
    for (const c of table.columns)
      if (c.comment) out.push(`COMMENT ON COLUMN ${q(table.name, dialect)}.${q(c.name, dialect)} IS ${sqlString(c.comment)};`)
  } else if (dialect === 'sqlserver') {
    if (table.comment) out.push(sqlServerDescription(table.comment, table.name))
    for (const c of table.columns) if (c.comment) out.push(sqlServerDescription(c.comment, table.name, c.name))
  }
  return out
}

const dollarQuote = (body: string) => {
  let tag = '$$'
  let i = 0
  while (body.includes(tag)) tag = `$fn${i++ || ''}$`
  return `${tag}\n${body.trim()}\n${tag}`
}

/** Generador sencillo de funciones + triggers para PostgreSQL (fallback). */
export function simpleTriggerSQL(schema: Schema): string {
  const out: string[] = []
  for (const f of schema.functions) {
    out.push(
      `CREATE OR REPLACE FUNCTION ${q(f.name, 'postgresql')}(${f.args ?? ''})\nRETURNS ${f.returns || 'trigger'}\nLANGUAGE ${f.language || 'plpgsql'}\nAS ${dollarQuote(f.body || 'BEGIN\n  RETURN NEW;\nEND;')};`,
    )
    if (f.comment) out.push(`COMMENT ON FUNCTION ${q(f.name, 'postgresql')}(${f.args ?? ''}) IS ${sqlString(f.comment)};`)
  }
  for (const t of schema.triggers) {
    const table = schema.tables.find((x) => x.id === t.tableId)
    const fn = schema.functions.find((x) => x.id === t.functionId)
    if (!table || !fn) continue
    out.push(
      `CREATE TRIGGER ${q(t.name, 'postgresql')}\n  ${t.timing} ${t.events.join(' OR ')} ON ${q(table.name, 'postgresql')}\n  FOR EACH ${t.level}${
        t.condition ? `\n  WHEN (${t.condition})` : ''
      }\n  EXECUTE FUNCTION ${q(fn.name, 'postgresql')}();`,
    )
  }
  return out.join('\n\n')
}

/** ALTER TABLE … ENABLE/DISABLE TRIGGER (solo PostgreSQL; MySQL no permite desactivar triggers). */
export function triggerStateSQL(schema: Schema, trigger: Schema['triggers'][number], enabled: boolean, dialect: Dialect): string | null {
  if (dialect !== 'postgresql') return null
  const table = schema.tables.find((t) => t.id === trigger.tableId)?.name ?? schema.views?.find((v) => v.id === trigger.tableId)?.name
  if (!table) return null
  return `ALTER TABLE ${q(table, dialect)} ${enabled ? 'ENABLE' : 'DISABLE'} TRIGGER ${q(trigger.name, dialect)};`
}

/** DISABLE TRIGGER para los triggers desactivados (`enabled === false`). */
export function disabledTriggersSQL(schema: Schema, dialect: Dialect, triggers = schema.triggers): string[] {
  return triggers.filter((t) => t.enabled === false).map((t) => triggerStateSQL(schema, t, false, dialect)).filter((x): x is string => !!x)
}

/** Funciones + triggers del esquema en el dialecto indicado (PostgreSQL o MySQL). */
export function triggerSQL(schema: Schema, dialect: Dialect = 'postgresql'): string {
  try {
    if (triggerSQLProvider) return triggerSQLProvider(schema, dialect)
    return generateProceduralSQL(schema, dialect)
  } catch {
    return dialect === 'postgresql' ? simpleTriggerSQL(schema) : ''
  }
}

/** Definición SELECT sin punto y coma final. */
const viewBody = (v: View) => v.definition.trim().replace(/;+\s*$/, '')

export function createViewSQL(v: View, dialect: Dialect, opts: { comments?: boolean } = {}): string {
  const out: string[] = []
  const mat = v.materialized && dialect === 'postgresql'
  if (v.materialized && !mat) {
    out.push(lineComment(`"${v.name}" es una vista materializada; ${DIALECT_LABELS[dialect]} no las soporta: se crea como vista normal.`))
  }
  if (dialect === 'sqlite' && v.comment && opts.comments !== false) out.push(lineComment(v.comment))
  out.push(`CREATE ${mat ? 'MATERIALIZED ' : ''}VIEW ${q(v.name, dialect)} AS\n${viewBody(v) || 'SELECT 1'};`)
  if (opts.comments !== false && v.comment) {
    if (dialect === 'postgresql') out.push(`COMMENT ON ${mat ? 'MATERIALIZED ' : ''}VIEW ${q(v.name, dialect)} IS ${sqlString(v.comment)};`)
    else if (dialect === 'sqlserver')
      out.push(
        `EXEC sp_addextendedproperty @name = N'MS_Description', @value = N${sqlString(v.comment)}, @level0type = N'SCHEMA', @level0name = N'dbo', @level1type = N'VIEW', @level1name = N${sqlString(v.name)};`,
      )
  }
  return out.join('\n')
}

export function dropViewSQL(v: Pick<View, 'name' | 'materialized'>, dialect: Dialect, ifExists = true): string {
  const mat = v.materialized && dialect === 'postgresql'
  return `DROP ${mat ? 'MATERIALIZED ' : ''}VIEW ${ifExists ? 'IF EXISTS ' : ''}${q(v.name, dialect)};`
}

export function generateSQL(schema: Schema, dialect: Dialect = schema.dialect, opts: GenerateSQLOptions = {}): string {
  const { includeDrop = false, includeComments = true, includeTriggers = true, header = true } = opts
  const out: string[] = []
  if (header) out.push(lineComment(`Generado por DB Tracker · ${DIALECT_LABELS[dialect]} · ${new Date().toISOString()}`))

  const tables = orderTables(schema)
  const relations = resolveRelations(schema)

  const views = orderViews(schema.views ?? [])

  if (includeDrop) {
    const drops: string[] = []
    for (const v of [...views].reverse()) drops.push(dropViewSQL(v, dialect))
    if (dialect === 'mysql') drops.push('SET FOREIGN_KEY_CHECKS = 0;')
    for (const t of [...tables].reverse()) {
      if (dialect === 'sqlserver') drops.push(`DROP TABLE IF EXISTS ${q(t.name, dialect)};`)
      else drops.push(`DROP TABLE IF EXISTS ${q(t.name, dialect)}${dialect === 'postgresql' ? ' CASCADE' : ''};`)
    }
    if (dialect === 'postgresql') for (const e of schema.enums) drops.push(`DROP TYPE IF EXISTS ${q(e.name, dialect)} CASCADE;`)
    if (dialect === 'mysql') drops.push('SET FOREIGN_KEY_CHECKS = 1;')
    out.push(drops.join('\n'))
  }

  if (dialect === 'postgresql') {
    for (const e of schema.enums) out.push(`CREATE TYPE ${q(e.name, dialect)} AS ENUM (${e.values.map(sqlString).join(', ')});`)
  } else if (dialect === 'sqlite') {
    out.push('PRAGMA foreign_keys = ON;')
  }

  for (const t of tables) {
    const inline = dialect === 'sqlite' ? relations.filter((r) => r.target.id === t.id) : []
    out.push(createTableSQL(schema, t, dialect, inline))
    if (includeComments) {
      const comments = commentStatements(t, dialect)
      if (comments.length) out.push(comments.join('\n'))
    }
  }

  const indexes: string[] = []
  for (const t of tables)
    for (const idx of t.indexes) {
      const s = createIndexSQL(t, idx, dialect)
      if (s) indexes.push(s)
    }
  if (indexes.length) out.push(indexes.join('\n'))

  if (dialect !== 'sqlite') {
    const fks = relations.map((r) => addForeignKeySQL(schema, r, dialect))
    if (fks.length) out.push(fks.join('\n'))
  }

  if (views.length) out.push(views.map((v) => createViewSQL(v, dialect, { comments: includeComments })).join('\n\n'))

  if (includeTriggers && (schema.functions.length || schema.triggers.length)) {
    if (dialect === 'postgresql' || dialect === 'mysql') {
      const warn = dialect === 'mysql' ? dialectWarnings(schema, dialect) : []
      if (warn.length) out.push(lineComment(warn.join('\n')))
      const trg = triggerSQL(schema, dialect).trim()
      if (trg) out.push(trg)
      const disabled = disabledTriggersSQL(schema, dialect)
      if (disabled.length) out.push(`${lineComment('Triggers desactivados')}\n${disabled.join('\n')}`)
      else if (dialect === 'mysql' && schema.triggers.some((t) => t.enabled === false))
        out.push(lineComment('MySQL no permite desactivar triggers: los marcados como desactivados se crean activos.'))
    } else {
      out.push(
        lineComment(
          `${schema.functions.length} función(es) y ${schema.triggers.length} trigger(s) definidos en PL/pgSQL; ` +
            `no se traducen automáticamente a ${DIALECT_LABELS[dialect]}.`,
        ),
      )
    }
  }

  return out.join('\n\n') + '\n'
}
